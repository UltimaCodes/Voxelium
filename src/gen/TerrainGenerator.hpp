#pragma once

#include "world/Chunk.hpp"
#include "world/ChunkPos.hpp"

#include <FastNoise/FastNoise.h>
#include <glm/glm.hpp>

namespace vx {

// Sea level, shared so spawn placement can keep the player above water rather than
// dropping them onto a seabed.
inline constexpr int kSeaLevelForSpawn = 62;

// Real world gen: warped fractal simplex heights, biome amplitude from a low-frequency
// continentalness noise through a spline, cheese + noodle caves, glow deposits on cave
// floors. Fully deterministic from the seed and chunk-independent, every value is a
// pure function of world coordinates. Node trees are immutable after construction, so
// one instance serves all worker threads.
class TerrainGenerator {
public:
    // Which generator made a world. A world remembers its version (WorldStore, world.cfg) and
    // is always generated by that one, so the land around anything built in it never changes
    // under it. 1 is the original terrain; new worlds get the latest.
    static constexpr int kLatestVersion = 2;
    explicit TerrainGenerator(int seed, int version = kLatestVersion);
    int version() const { return m_version; }

    // detailed=false skips caves + glow deposits (which live underground and vanish under
    // the LOD downsample anyway), the bulk of gen cost. surface, water and trees still
    // generate, so a coarse chunk looks right from above and nothing pops in when the
    // camera approaches and ChunkManager re-generates it detailed (only caves fill in,
    // and those are underground).
    void generate(Chunk& chunk, ChunkPos pos, bool detailed = true) const;
    int surfaceHeight(int wx, int wz) const; // for spawn placement
    // Where a player starts: dry land near the origin. Version 1 always answered (16, 16), and
    // keeps doing so; a world with real seas could put that in the middle of one.
    glm::ivec2 spawnColumn() const;
    int seed() const { return m_seed; }

    // What the ground at a column is, as 0..1 weights: open sea (deeper is higher), the sandy
    // band around it, and desert. Pure function of the seed, same as everything here, so the
    // ambience director can ask where the player is standing without touching the world.
    struct BiomeSample {
        float ocean = 0.0f;
        float beach = 0.0f;
        float desert = 0.0f;
    };
    BiomeSample biomeAt(int wx, int wz) const;

    // Everything the far-terrain horizon needs about a column, in one noise evaluation: its
    // height, how desert it is, and how wooded (0 open grass .. 1 dense forest).
    struct FarSample {
        int h;
        float desert;
        float forest;
    };
    FarSample farSample(int wx, int wz) const;

    // The height snow starts at in this column. Shared with the far horizon so the two agree
    // where the snowcaps begin.
    int snowLineAt(int wx, int wz) const;

    // What, if anything, stands in a 96-block structure cell: 0 nothing, 1 shipwreck, 2 desert ruins,
    // 3 lighthouse, with the x/z it is anchored at. Public so a harness can find one to look at.
    struct StructureSite {
        int kind = 0;
        int x = 0, z = 0;
        int h = 0; // ground height at the anchor
    };
    StructureSite structureSite(int cellX, int cellZ) const;
    // Version 2: whether a pyramid stands in kPyramidCell cell (cx, cz) (kind 4, h = the level its
    // base course sits at), and how big it is.
    static constexpr int kPyramidCell = 160;
    StructureSite pyramidSite(int cellX, int cellZ, int& halfWidth) const;

    // Version 2's mineshafts: one candidate network per kShaftCell cell, a level random walk of
    // timber-framed corridors, built by every chunk it crosses from the cell alone. Public so a
    // harness can find one to look at.
    struct ShaftSeg {
        int x, z;  // where the corridor starts, on its centre line
        int dir;   // 0 +x, 1 -x, 2 +z, 3 -z
        int len;
    };
    static constexpr int kShaftCell = 128;
    static constexpr int kShaftMaxSegs = 16;
    // The network in cell (cx, cz), if it has one (0 corridors if not): its corridors and the
    // level they run at.
    int shaftNetwork(int cx, int cz, int& y, ShaftSeg* out) const;

private:
    // Final height of a column and how desert it is. Every place that needs to agree about the
    // ground (chunks, trees, foliage, spawn, light) goes through this one shaping function.
    struct Column {
        int h;
        float desert;
        // Version 2: roughly how many blocks inland from the sea this is (negative out at sea).
        // Beach sand, shells and palms keep to the coast by it. Version 1 leaves it 0 and never
        // reads it.
        float coast = 0.0f;
    };
    Column column(int wx, int wz) const;
    static Column shapeColumn(float heightNoise, float continent, float arid, float dune,
                              int wx, int wz, int seed);
    // Version 2's inputs for one column, and the shaping that turns them into ground.
    struct Noise2 {
        float cont, belt, beltOn, ridge, hilly, aridity, hills, dune;
        // the slopes of the continent, belt and aridity fields, per block (central differences):
        // each is turned into a distance in blocks from its edge
        float contGx, contGz, beltGx, beltGz, aridGx, aridGz;
        float lookD; // how far the coast is by the look around (coastLook in the .cpp)
    };
    static Column shapeColumn2(const Noise2& n, int wx, int wz, int seed);
    // Version 1: the chunk's 32 x 32 columns.
    void columnGrid(int baseX, int baseZ, int (*heights)[kChunkSize], float (*desert)[kChunkSize]) const;
    // Version 2: an n x n block of columns from (x0, z0), row-major (x + z * n). The chunk asks
    // for a ring beyond itself, so caves can see how close the ground comes from the side.
    void columnGrid2(int x0, int z0, int n, int* heights, float* desert, float* coast) const;
    static constexpr int kSidePad = 4;

    void placeTrees(Chunk& chunk, ChunkPos pos) const;
    // Lighthouses on the coast, shipwrecks on the shallow seabed and ruins in the desert: one
    // candidate per 96-block cell, built from the anchor's position alone like the trees are, so
    // every chunk a structure crosses builds the same one with no neighbour lookups.
    void placeStructures(Chunk& chunk, ChunkPos pos) const;
    // coast: version 2's blocks-inland per column (null for version 1); rock: version 2's bare
    // rock faces (0 soil, 1 rock, 2 rock even above the snow line), which grow nothing
    void placeFoliage(Chunk& chunk, ChunkPos pos, const int (*heights)[kChunkSize],
                      const float (*desert)[kChunkSize], const float (*coast)[kChunkSize],
                      const std::uint8_t (*rock)[kChunkSize]) const;
    // Whether this column of ground is a beach: sand at the waterline, and for version 2 only
    // where the sea actually is (low ground by an inland lake is grass).
    bool isBeach(int h, float coast) const;
    void decorateSea(Chunk& chunk, int baseX, int baseY, int baseZ, int x, int z, int h) const;
    void placePalm(Chunk& chunk, ChunkPos pos, int tx, int tz, int surf,
                   std::uint32_t rv) const;

    int m_seed;
    int m_version;
    FastNoise::SmartNode<> m_height;    // domain-warped fbm, [-1,1]
    FastNoise::SmartNode<> m_continent; // very low frequency, drives the spline
    FastNoise::SmartNode<> m_arid;      // very low frequency, where it is hot and dry
    FastNoise::SmartNode<> m_dune;      // crest lines for the desert's dunes
    FastNoise::SmartNode<> m_cheese;    // 3d fbm cave blobs
    // Worm tunnels are the intersection of these two: the places where BOTH are near zero
    // form a 1D curve through the volume, and carving a radius around it gives a tunnel.
    // One ridged field on its own only ever gives sheets, which is what the old noodle was.
    FastNoise::SmartNode<> m_wormA;
    FastNoise::SmartNode<> m_wormB;

    // Version 2 (see shapeColumn2).
    FastNoise::SmartNode<> m_cont2;   // continents and seas, thousands of blocks across, warped
    FastNoise::SmartNode<> m_belt;    // mountain range axes: where it crosses zero
    FastNoise::SmartNode<> m_beltOn;  // which stretches of those axes rise into a range
    FastNoise::SmartNode<> m_ridge;   // the ranges' ridgelines
    FastNoise::SmartNode<> m_hilly;   // flat plains against rolling country
    FastNoise::SmartNode<> m_aridity; // deserts: one smooth warped field
    // Version 2's caves (see carveCaves2).
    FastNoise::SmartNode<> m_cavern;     // 3d: the big chambers, flattened
    FastNoise::SmartNode<> m_tunnelA;    // 3d: a second, longer pair of worm fields
    FastNoise::SmartNode<> m_tunnelB;
    FastNoise::SmartNode<> m_tunnelW;    // 3d: how wide those tunnels are, along their length
    FastNoise::SmartNode<> m_ravine;     // 2d: ravine paths, where it crosses zero
    FastNoise::SmartNode<> m_ravineMask; // 2d: the few places a ravine actually opens
    // groundMin: the lowest surface within kSidePad of each column, which is what a cave has to
    // stay under to not break out of a slope
    void carveCaves2(Chunk& chunk, int baseX, int baseY, int baseZ, const int (*heights)[kChunkSize],
                     const int (*groundMin)[kChunkSize]) const;
    void placeMineshafts(Chunk& chunk, ChunkPos pos, const int (*heights)[kChunkSize]) const;
    void placePyramids(Chunk& chunk, ChunkPos pos) const;
};

} // namespace vx
